import assert from 'node:assert/strict';
import { STORAGE_KEYS, readStoredText, writeStoredText } from './browser-storage.js';
import { readDraft, writeDraft, removeDraft } from './features/draft-store.js';
const values=new Map();
globalThis.localStorage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const legacy={title:'Keep my draft',ingredients:[{kind:'ingredient',name:'Carrot',amount:'2'}],steps:[{text:'Chop.'}],categories:['Dinner']};
values.set('cookingdb:add-recipe:draft:v2',JSON.stringify(legacy));
assert.deepEqual(readDraft(),legacy);
assert.equal(writeDraft(legacy),true);
assert.equal(removeDraft(),true);
assert.equal(readDraft(),null);
values.set(STORAGE_KEYS.draft,JSON.stringify({title:'Recover title',ingredients:{},steps:null,categories:3}));
assert.deepEqual(readDraft(),{title:'Recover title',ingredients:[],steps:[],categories:[]});
values.set(STORAGE_KEYS.draft,'{broken');assert.equal(readDraft(),null);
Object.defineProperty(globalThis,'localStorage',{configurable:true,get(){throw new Error('storage disabled');}});
assert.equal(readStoredText(STORAGE_KEYS.draft),null);
assert.equal(writeStoredText(STORAGE_KEYS.draft,'test'),false);
assert.equal(readDraft(),null);
delete globalThis.localStorage;
console.log('Storage compatibility, malformed draft recovery, and unavailable storage passed.');
